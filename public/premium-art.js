  function r2(v) { return +v.toFixed(2); }
  // A ring of pointed tufts (manes, ruffs, feathers) as one path.
  function petals(cx, cy, r0, r1, count, width, rot) {
    var d = '';
    for (var i = 0; i < count; i++) {
      var a = (rot || 0) + i * Math.PI * 2 / count;
      var w = width * Math.PI * 2 / count;
      var bx1 = cx + r0 * Math.cos(a - w), by1 = cy + r0 * Math.sin(a - w);
      var bx2 = cx + r0 * Math.cos(a + w), by2 = cy + r0 * Math.sin(a + w);
      var tx = cx + r1 * Math.cos(a), ty = cy + r1 * Math.sin(a);
      var c1x = cx + (r0 + r1) * 0.55 * Math.cos(a - w * 0.9), c1y = cy + (r0 + r1) * 0.55 * Math.sin(a - w * 0.9);
      var c2x = cx + (r0 + r1) * 0.55 * Math.cos(a + w * 0.9), c2y = cy + (r0 + r1) * 0.55 * Math.sin(a + w * 0.9);
      d += 'M' + r2(bx1) + ',' + r2(by1) + 'Q' + r2(c1x) + ',' + r2(c1y) + ' ' + r2(tx) + ',' + r2(ty) + 'Q' + r2(c2x) + ',' + r2(c2y) + ' ' + r2(bx2) + ',' + r2(by2) + 'Z';
    }
    return d;
  }
  // Short fur strokes along an arc (texture on heads and chests).
  function furStrokes(cx, cy, r, from, to, count, len, tilt) {
    var d = '';
    for (var i = 0; i < count; i++) {
      var a = from + (to - from) * (i + 0.5) / count;
      var x = cx + r * Math.cos(a), y = cy + r * Math.sin(a);
      var b = a + (tilt || 0);
      d += 'M' + r2(x) + ',' + r2(y) + 'l' + r2(len * Math.cos(b)) + ',' + r2(len * Math.sin(b));
    }
    return d;
  }
  // Scattered dots as one path (stars, freckles, spots).
  function dots(pts) { return pts.map(function (p) { var r = p[2] || 1; return 'M' + r2(p[0] - r) + ',' + p[1] + 'a' + r + ',' + r + ' 0 1,0 ' + r2(2 * r) + ',0a' + r + ',' + r + ' 0 1,0 ' + r2(-2 * r) + ',0z'; }).join(''); }
  // A leaf (for falling-leaf loops and foliage).
  function leafD(x, y, s, a) {
    var c = Math.cos(a), si = Math.sin(a);
    function p(u, v) { return r2(x + (u * c - v * si) * s) + ',' + r2(y + (u * si + v * c) * s); }
    return 'M' + p(-1, 0) + 'Q' + p(0, -0.75) + ' ' + p(1, 0) + 'Q' + p(0, 0.75) + ' ' + p(-1, 0) + 'Z';
  }
  // Leaves/flakes that drift down and fade (falling version of k.risers).
  function fallers(k, pts, mk, dist, dur) {
    return pts.map(function (q, i) {
      var d = dur || 5;
      var off = i * (d / pts.length);
      return k.G([k.G([mk(q[0], q[1], q[2] || 3, i)], { o: [q[0], q[1]], a: [['rot', -25, 25, d / 2.5, off]] })],
        { o: [q[0], q[1]], a: [['rise', -(dist || 40), 0, d, off], ['fade', 1, 0, d, off], ['tx', -4, 4, d / 2, off]], fx: true });
    });
  }
  // A soft shadow under a head, and a breathing body.
  function shadow(k, cx, cy, rx, ry, o) { return k.E(cx, cy, rx, ry, '#000000', o == null ? 0.22 : o); }

