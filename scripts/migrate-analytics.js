#!/usr/bin/env node
'use strict';

/*
 * Puts the GA4 tag on every indexable page.
 *
 * Before this ran, analytics existed on exactly nine files - index.html,
 * chat.html, landing.html and the six policy/marketing pages that are
 * hand-maintained. Every page the SEO build produces had none: 74 landing
 * pages, 22 blog posts, the 177 country/city/language pages and the 16
 * localized homepages, which is to say the entire organic surface and all of
 * the traffic this project exists to earn.
 *
 * The cost of that is not subtle. There was no way to answer which landing
 * page brought a visitor, which keyword produced a call, whether the city
 * pages convert at all, or what a thousand sessions on any page are worth -
 * so every ad-density and content decision was a guess dressed up as a
 * judgement call. Measurement has to come first; it is what makes the rest of
 * this work checkable.
 *
 * Why a sweep rather than an edit to the page templates: three page sets
 * (scripts/geo-pages.js, pages-extra2.js, blog-extra2.js - 177+ pages) are
 * generated by scripts that `npm run build:seo` no longer runs. They ship from
 * disk and Google crawls them, but no template change can reach them. SEO.md
 * documents why reviving those generators destroys 14-18% of the pages' visible
 * text, so the established pattern for anything sitewide is a sweep over
 * public/**\/*.html. scripts/migrate-schema.js and scripts/migrate-adsterra.js
 * both work this way and this follows them.
 *
 * Idempotent: a page that already carries the tag is skipped, so on a correct
 * site this reports 0 files.
 */

const fs = require('fs');
const path = require('path');

const publicDir = path.join(__dirname, '..', 'public');

// The same property the nine hand-maintained pages already report to. A second
// measurement ID would split the site's sessions across two properties and make
// the totals wrong in both.
const MEASUREMENT_ID = 'G-713E3C1RH1';

/*
 * Loaded at the end of <body>, matching public/index.html.
 *
 * The tag is async, so where it sits does not decide whether it runs - only
 * when it starts competing with the page's own CSS and HTML for bandwidth on a
 * slow mobile connection. Last is therefore the right place, and it is the
 * reasoning the homepage already documents at its own tag.
 *
 * There is deliberately no <link rel="preconnect"> to googletagmanager.com
 * here. On these pages the largest contentful paint is text behind a 13 kB
 * stylesheet, and opening a third-party TLS connection early to save a few
 * milliseconds on a script that has not been requested yet trades LCP for
 * analytics latency. The homepage preconnects because it is a much heavier
 * document; these pages are not.
 */
const SNIPPET = `<!-- Google tag (gtag.js) - see scripts/migrate-analytics.js -->
<script async src="https://www.googletagmanager.com/gtag/js?id=${MEASUREMENT_ID}"></script>
<script>
  window.dataLayer = window.dataLayer || [];
  function gtag(){dataLayer.push(arguments);}
  gtag('js', new Date());
  gtag('config', '${MEASUREMENT_ID}');
</script>
`;

function htmlFiles(dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const fullPath = path.join(dir, entry.name);
    if (entry.isDirectory()) return htmlFiles(fullPath);
    return entry.isFile() && entry.name.endsWith('.html') ? [fullPath] : [];
  });
}

let updated = 0;
let skipped = 0;
for (const file of htmlFiles(publicDir)) {
  const before = fs.readFileSync(file, 'utf8');

  // Already tagged - by this sweep or by hand. Matching on the host rather than
  // on this snippet's exact text means a hand-written tag is never duplicated.
  if (before.includes('googletagmanager.com/gtag/js')) {
    skipped += 1;
    continue;
  }

  // No closing body tag means this is not a page shell; leave it alone rather
  // than appending a script to something whose structure is unknown.
  if (!before.includes('</body>')) continue;

  const html = before.replace('</body>', `${SNIPPET}</body>`);
  fs.writeFileSync(file, html);
  updated += 1;
}

console.log(`Analytics: tagged ${updated} HTML files (${skipped} already had it).`);
