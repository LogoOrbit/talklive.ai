#!/usr/bin/env python3
"""Builds res/values-<lang>/strings.xml from tools/i18n/<lang>.json.

Each JSON maps the English key (see en.json, exported from values/strings.xml)
to its translation. Missing keys fall back to English. Placeholders (%1$s,
%2$d...) must match the English exactly or the build stops.

    python3 tools/i18n/build.py
"""
import json, os, re, sys
from xml.sax.saxutils import escape

HERE = os.path.dirname(os.path.abspath(__file__))
RES = os.path.join(HERE, '..', '..', 'app', 'src', 'main', 'res')
PH = re.compile(r'%\d\$[sd]')
en = json.load(open(os.path.join(HERE, 'en.json'), encoding='utf-8'))
DONT = {'app_name', 'plus', 'tic_tac_toe'}

def android_escape(s):
    s = escape(s)
    s = s.replace('\\', '\\\\').replace("'", "\\'").replace('"', '\\"')
    if s.startswith('@') or s.startswith('?'):
        s = '\\' + s
    return s

bad = 0
for f in sorted(os.listdir(HERE)):
    if not f.endswith('.json') or f == 'en.json':
        continue
    lang = f[:-5]
    tr = json.load(open(os.path.join(HERE, f), encoding='utf-8'))
    strings, plurals = [], {}
    for k, v in tr.items():
        if k in DONT or k.split('#')[0] not in {x.split('#')[0] for x in en}:
            continue
        src = en.get(k)
        if src is None:
            continue
        if sorted(PH.findall(src)) != sorted(PH.findall(v)):
            print(f'{lang}: placeholder mismatch in {k}: {v!r}', file=sys.stderr)
            bad += 1
            continue
        if '#' in k:
            name, q = k.split('#')
            plurals.setdefault(name, []).append((q, v))
        else:
            strings.append((k, v))
    out_dir = os.path.join(RES, f'values-{lang}')
    os.makedirs(out_dir, exist_ok=True)
    lines = ['<?xml version="1.0" encoding="utf-8"?>', '<!-- Generated by tools/i18n/build.py from tools/i18n/%s.json. Do not edit. -->' % f, '<resources>']
    for k, v in strings:
        lines.append(f'    <string name="{k}">{android_escape(v)}</string>')
    # Every quantity a locale may ask for; missing ones reuse "other".
    NEEDED = {'ar': ['zero', 'one', 'two', 'few', 'many', 'other'], 'ru': ['one', 'few', 'many', 'other'],
              'pl': ['one', 'few', 'many', 'other'], 'fa': ['one', 'other'], 'ur': ['one', 'other']}
    for name, items in plurals.items():
        have = dict(items)
        for q in NEEDED.get(lang, []):
            if q not in have and 'other' in have:
                items.append((q, have['other']))
        lines.append(f'    <plurals name="{name}">')
        for q, v in items:
            lines.append(f'        <item quantity="{q}">{android_escape(v)}</item>')
        lines.append('    </plurals>')
    lines.append('</resources>')
    open(os.path.join(out_dir, 'strings.xml'), 'w', encoding='utf-8').write('\n'.join(lines) + '\n')
    print(f'{lang}: {len(strings) + sum(len(i) for i in plurals.values())}/{len(en)} strings')
sys.exit(1 if bad else 0)
