// Converts the website's movie-character avatars (public/characters.js) into
// Android vector drawables plus a Kotlin list. Stored as "c:<id>", like the site.
//
//   node android-native/tools/gen-characters.js
const fs = require('fs');
const path = require('path');
const vm = require('vm');
const { toVector } = require('./gen-animals.js');
const root = path.join(__dirname, '..', '..');
const sandbox = { window: {}, document: {} };
vm.runInNewContext(fs.readFileSync(path.join(root, 'public', 'characters.js'), 'utf8'), sandbox);
const { list } = sandbox.window.TalkLiveCharacters;
// Which faces are free comes from the website (isFree in animals.js), so the
// app cannot disagree with it; every other animal and character is Plus.
const animalSandbox = { window: {} };
vm.runInNewContext(fs.readFileSync(path.join(root, 'public', 'animals.js'), 'utf8'), animalSandbox);
const { isFree, list: animalList } = animalSandbox.window.TalkLiveAnimals;
// The characters with a Plus scene are the ones avatar-scenes.css styles. The
// app draws that scene behind the art without its round tile (AvatarScenes.kt).
const sceneIds = new Set([...fs.readFileSync(path.join(root, 'public', 'avatar-scenes.css'), 'utf8')
  .matchAll(/\.tl-s-(\w+) \.tl-sc \{/g)].map((m) => m[1]));
const resDir = path.join(__dirname, '..', 'app', 'src', 'main', 'res', 'drawable');
const ktFile = path.join(__dirname, '..', 'app', 'src', 'main', 'java', 'app', 'talklive', 'ui', 'animals', 'Characters.kt');
const fromSite = (xml) => xml.replace(/gen-animals\.js from public\/animals\.js/g, 'gen-characters.js from public/characters.js');
const rows = [];
const bare = [];
for (const c of list) {
  const svg = c.art();
  const name = 'character_' + c.id.replace(/[^a-z0-9]/g, '_');
  fs.writeFileSync(path.join(resDir, name + '.xml'), fromSite(toVector(svg)));
  if (sceneIds.has(c.id)) {
    fs.writeFileSync(path.join(resDir, name + '_bare.xml'), fromSite(toVector(svg.replace(/^<circle[^>]*\/>/, ''))));
    bare.push(`    "c:${c.id}" to R.drawable.${name}_bare,`);
  }
  const bg = (svg.match(/^<circle[^>]*fill="(#[0-9a-fA-F]{6})"/) || [, '#6c5ce7'])[1];
  rows.push(`    Animal("c:${c.id}", ${JSON.stringify(c.name)}, "", Color(0xFF${bg.slice(1).toUpperCase()}), R.drawable.${name}),`);
}
const free = [
  ...animalList.filter((a) => isFree('a:' + a.id)).map((a) => `    "${a.id}",`),
  ...list.filter((c) => isFree('c:' + c.id)).map((c) => `    "c:${c.id}",`),
];
fs.writeFileSync(ktFile, `// Generated by tools/gen-characters.js from public/characters.js. Do not edit.
package app.talklive.ui.animals

import androidx.compose.ui.graphics.Color
import app.talklive.R

/** Movie-character avatars, the website's second avatar family ("c:<id>"). */
val Characters: List<Animal> = listOf(
${rows.join('\n')}
)

/** The faces a free account may pick (isFree in public/animals.js); every other animal and character is Plus. */
val FREE_FACES: Set<String> = setOf(
${free.join('\n')}
)

/** Characters with a Plus scene (public/avatar-scenes.css), with their art minus the round tile the scene replaces. */
val CharacterBare: Map<String, Int> = mapOf(
${bare.join('\n')}
)
`);
console.log(`wrote ${list.length} characters, ${bare.length} scenes`);
