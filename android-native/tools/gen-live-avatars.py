#!/usr/bin/env python3
"""Makes a blinking version of every avatar for Plus members.

For each res/drawable/animal_*.xml and character_*.xml it finds the eyes (a
dark #1F2637 circle followed by its white glint, as gen-animals.js draws
them), wraps each eye in a group pivoted on its centre, and writes
<name>_live.xml: an animated-vector whose one run is a blink. The app plays
it every few seconds. Avatars without eyes like that get no file.

Run after gen-animals.js: python3 tools/gen-live-avatars.py
"""
import glob, os, re

RES = os.path.join(os.path.dirname(__file__), '..', 'app', 'src', 'main', 'res', 'drawable')
PATH_RE = re.compile(r'    <path\b.*?/>\n', re.S)
CIRCLE_RE = re.compile(r'android:pathData="M([\d.]+),([\d.]+)a([\d.]+),([\d.]+) 0 1,0')

def blink(name):
    return f'''    <target android:name="{name}">
        <aapt:attr name="android:animation">
            <set android:ordering="sequentially">
                <objectAnimator android:propertyName="scaleY" android:duration="80" android:valueFrom="1" android:valueTo="0.1" android:valueType="floatType" />
                <objectAnimator android:propertyName="scaleY" android:duration="120" android:valueFrom="0.1" android:valueTo="1" android:valueType="floatType" />
            </set>
        </aapt:attr>
    </target>
'''

made = 0
live = []
for src in sorted(glob.glob(os.path.join(RES, 'animal_*.xml')) + glob.glob(os.path.join(RES, 'character_*.xml'))):
    if src.endswith('_live.xml'):
        continue
    xml = open(src).read()
    paths = PATH_RE.findall(xml)
    out, eyes, i = [], [], 0
    while i < len(paths):
        p = paths[i]
        m = CIRCLE_RE.search(p)
        nxt = paths[i + 1] if i + 1 < len(paths) else ''
        if m and '#1F2637' in p and '#FFFFFF' in nxt:
            cx = float(m.group(1)) + float(m.group(3)); cy = float(m.group(2))
            name = f'eye{len(eyes)}'
            eyes.append(name)
            out.append(f'    <group android:name="{name}" android:pivotX="{cx:g}" android:pivotY="{cy:g}">\n'
                       + p.replace('    <path', '        <path') + nxt.replace('    <path', '        <path') + '    </group>\n')
            i += 2
        else:
            out.append(p); i += 1
    if not eyes:
        continue
    head = xml[xml.index('<vector'):xml.index('>', xml.index('<vector')) + 1]
    vector = head + '\n' + ''.join(out) + '</vector>'
    vector = vector.replace(' xmlns:android="http://schemas.android.com/apk/res/android"', '')
    avd = ('<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by tools/gen-live-avatars.py. Do not edit. -->\n'
           '<animated-vector xmlns:android="http://schemas.android.com/apk/res/android" xmlns:aapt="http://schemas.android.com/aapt">\n'
           '    <aapt:attr name="android:drawable">\n'
           + '\n'.join('        ' + l if l else l for l in vector.split('\n')) + '\n    </aapt:attr>\n'
           + ''.join(blink(n) for n in eyes) + '</animated-vector>\n')
    open(src[:-4] + '_live.xml', 'w').write(avd)
    made += 1
    live.append(os.path.basename(src)[:-4])
# The app looks them up from this map (explicit R ids, so resource shrinking keeps them).
kt = os.path.join(os.path.dirname(__file__), '..', 'app', 'src', 'main', 'java', 'app', 'talklive', 'ui', 'animals', 'LiveAvatars.kt')
open(kt, 'w').write('// Generated by tools/gen-live-avatars.py. Do not edit.\npackage app.talklive.ui.animals\n\nimport app.talklive.R\n\n/** Avatar drawable -> its blinking version, for Plus members. */\nval LiveAvatars: Map<Int, Int> = mapOf(\n' + ''.join(f'    R.drawable.{n} to R.drawable.{n}_live,\n' for n in live) + ')\n')
print(f'{made} live avatars written')
