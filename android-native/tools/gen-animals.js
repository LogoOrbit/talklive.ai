// Converts the website's spirit animals (public/animals.js) into Android
// vector drawables plus a Kotlin list, so both apps show identical artwork.
//
//   node android-native/tools/gen-animals.js
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const root = path.join(__dirname, '..', '..');
const src = fs.readFileSync(path.join(root, 'public', 'animals.js'), 'utf8');
const sandbox = { window: {} };
vm.runInNewContext(src, sandbox);
const { list } = sandbox.window.TalkLiveAnimals;

const resDir = path.join(__dirname, '..', 'app', 'src', 'main', 'res', 'drawable');
const ktFile = path.join(__dirname, '..', 'app', 'src', 'main', 'java', 'app', 'talklive', 'ui', 'animals', 'Animals.kt');

const attrs = (s) => Object.fromEntries([...s.matchAll(/([a-z-]+)="([^"]*)"/g)].map((m) => [m[1], m[2]]));
const n = (v) => Number(v);
const fmt = (v) => +(+v).toFixed(3);

function color(c) {
  if (!c || c === 'none') return null;
  if (/^#[0-9a-f]{3}$/i.test(c)) c = '#' + c.slice(1).split('').map((x) => x + x).join('');
  const rgba = c.match(/^rgba\((\d+),\s*(\d+),\s*(\d+),\s*([\d.]+)\)$/);
  if (rgba) {
    const h = (v) => Math.round(+v).toString(16).padStart(2, '0');
    return ('#' + h(+rgba[4] * 255) + h(rgba[1]) + h(rgba[2]) + h(rgba[3])).toUpperCase();
  }
  if (!/^#[0-9a-f]{6}$/i.test(c)) throw new Error('unsupported colour ' + c);
  return c.toUpperCase();
}

function ellipsePath(cx, cy, rx, ry) {
  return `M${fmt(cx - rx)},${fmt(cy)}a${fmt(rx)},${fmt(ry)} 0 1,0 ${fmt(2 * rx)},0a${fmt(rx)},${fmt(ry)} 0 1,0 ${fmt(-2 * rx)},0z`;
}

function toVector(svg) {
  const out = [];
  for (const m of svg.matchAll(/<(circle|ellipse|path)\s([^>]*?)\/>/g)) {
    const [, tag, raw] = m;
    const a = attrs(raw);
    let d;
    if (tag === 'circle') d = ellipsePath(n(a.cx), n(a.cy), n(a.r), n(a.r));
    else if (tag === 'ellipse') d = ellipsePath(n(a.cx), n(a.cy), n(a.rx), n(a.ry));
    else d = a.d;
    const props = [`android:pathData="${d}"`];
    const fill = color(a.fill);
    if (fill) props.push(`android:fillColor="${fill}"`);
    const stroke = color(a.stroke);
    if (stroke) {
      props.push(`android:strokeColor="${stroke}"`, `android:strokeWidth="${a['stroke-width'] || 1}"`);
      if (a['stroke-linecap']) props.push(`android:strokeLineCap="${a['stroke-linecap']}"`);
      if (a['stroke-linejoin']) props.push(`android:strokeLineJoin="${a['stroke-linejoin']}"`);
    }
    if (a.opacity) {
      if (fill) props.push(`android:fillAlpha="${a.opacity}"`);
      if (stroke) props.push(`android:strokeAlpha="${a.opacity}"`);
    }
    let el = `    <path ${props.join('\n        ')} />`;
    const rot = a.transform && a.transform.match(/rotate\(([-\d.]+)\s+([-\d.]+)\s+([-\d.]+)\)/);
    if (a.transform && !rot) throw new Error('unsupported transform ' + a.transform);
    if (rot) {
      el = `    <group android:rotation="${rot[1]}" android:pivotX="${rot[2]}" android:pivotY="${rot[3]}">\n    ${el}\n    </group>`;
    }
    out.push(el);
  }
  const leftover = svg.replace(/<(circle|ellipse|path)\s[^>]*?\/>/g, '').trim();
  if (leftover) throw new Error('unconverted markup: ' + leftover.slice(0, 80));
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/gen-animals.js from public/animals.js. Do not edit. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="64dp" android:height="64dp" android:viewportWidth="64" android:viewportHeight="64">
${out.join('\n')}
</vector>
`;
}

module.exports = { toVector };
if (require.main !== module) return;
const entries = [];
for (const a of list) {
  fs.writeFileSync(path.join(resDir, `animal_${a.id}.xml`), toVector(a.art()));
  const esc = (s) => s.replace(/\\/g, '\\\\').replace(/"/g, '\\"');
  entries.push(`    Animal("${a.id}", "${esc(a.name)}", "${esc(a.trait)}", Color(0xFF${color(a.color).slice(1)}), R.drawable.animal_${a.id}),`);
}
fs.mkdirSync(path.dirname(ktFile), { recursive: true });
fs.writeFileSync(ktFile, `// Generated by tools/gen-animals.js from public/animals.js. Do not edit.
package app.talklive.ui.animals

import androidx.compose.ui.graphics.Color
import app.talklive.R

data class Animal(val id: String, val name: String, val trait: String, val color: Color, val icon: Int)

/** The spirit animals, in the website's picker order. */
val Animals: List<Animal> = listOf(
${entries.join('\n')}
)

private val byId = (Animals + Characters).associateBy { it.id }

fun animalById(id: String?): Animal? = id?.let { byId[it] }
`);
console.log(`wrote ${list.length} animals`);
